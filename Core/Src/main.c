#elif ((APP_MODE == APP_MODE_SPEED_TEST) || \
       (APP_MODE == APP_MODE_STRAIGHT_TEST) || \
       (APP_MODE == APP_MODE_FOLLOW_TEST) || \
       (APP_MODE == APP_MODE_DUTY_TEST))

    MotionTest_Run();

#elif (APP_MODE == APP_MODE_LINE_SENSOR_TEST)

